#!/usr/bin/env python3
"""Refresh the editor tree's file and folder icons from the Material Icon Theme.

`editor.explorer.icons` (#701) draws an icon beside each row of the editor's
file tree, picked by file name and extension the way VS Code's Material Icon
Theme picks them (MIT, github.com/material-extensions/vscode-material-icon-theme).
This script turns one release of that theme into what the app builds from:

    assets/explorer-icons/<icon>.svg          every icon a file name or
                                              extension maps to, plus the
                                              plain file and the closed and
                                              open folder
    assets/explorer-icons/LICENSE             the theme's licence
    infiniterm-core/src/explorer_icon_table.rs  name and extension tables
                                              (explorer_icons.rs reads them)
    infiniterm-ui/src/explorer_icon_svgs.rs   the SVG bytes, embedded
                                              (explorer_icons.rs in ui serves
                                              them to gpui)

Folder-name icons (a `src` folder's own picture) are left out: the setting
asks for a closed and an open folder only. The `light` variants are left out
too; the dark set is drawn on every theme.

    tools/explorer-icons.py <unpacked vsix dir>

Get the release from Open VSX (PKief/material-icon-theme), unzip it, and pass
the folder that holds `extension/`. Run `make check` after: the tests hold a
few well-known names to their icons.
"""
import json
import os
import shutil
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(REPO, "assets", "explorer-icons")
CORE_TABLE = os.path.join(REPO, "infiniterm-core", "src", "explorer_icon_table.rs")
UI_TABLE = os.path.join(REPO, "infiniterm-ui", "src", "explorer_icon_svgs.rs")


def rust_str(s):
    # A Rust string literal: UTF-8 as it is (json's `\uXXXX` is not Rust's
    # `\u{XXXX}`), only the quote and the backslash escaped.
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    ext = os.path.join(sys.argv[1], "extension")
    manifest = json.load(open(os.path.join(ext, "dist", "material-icons.json")))
    version = json.load(open(os.path.join(ext, "package.json")))["version"]
    defs = manifest["iconDefinitions"]

    # Keys are matched lowercased; the manifest's are already, but a stray
    # capital would never match, so fold them here.
    names = {k.lower(): v for k, v in manifest["fileNames"].items()}
    exts = {k.lower(): v for k, v in manifest["fileExtensions"].items()}
    special = {
        "file": manifest["file"],
        "folder": manifest["folder"],
        "folder_open": manifest["folderExpanded"],
    }
    used = sorted(set(names.values()) | set(exts.values()) | set(special.values()))

    if os.path.isdir(ASSETS):
        shutil.rmtree(ASSETS)
    os.makedirs(ASSETS)
    for icon in used:
        src = os.path.join(ext, "dist", defs[icon]["iconPath"])
        shutil.copyfile(os.path.normpath(src), os.path.join(ASSETS, icon + ".svg"))
    shutil.copyfile(os.path.join(ext, "LICENSE.txt"), os.path.join(ASSETS, "LICENSE"))

    with open(CORE_TABLE, "w") as f:
        f.write(
            "//! Generated by tools/explorer-icons.py from the Material Icon Theme\n"
            f"//! {version} (MIT, assets/explorer-icons/LICENSE). Do not edit by hand:\n"
            "//! run the script on a newer release instead. `explorer_icons.rs` reads\n"
            "//! these tables; both are sorted by key for a binary search.\n\n"
        )
        for key, value in special.items():
            f.write(f"pub const {key.upper()}: &str = {rust_str(value)};\n")
        for title, table in (("FILE_NAMES", names), ("FILE_EXTENSIONS", exts)):
            f.write(f"\npub const {title}: &[(&str, &str)] = &[\n")
            for k in sorted(table):
                f.write(f"    ({rust_str(k)}, {rust_str(table[k])}),\n")
            f.write("];\n")

    with open(UI_TABLE, "w") as f:
        f.write(
            "//! Generated by tools/explorer-icons.py: the editor tree's icons\n"
            f"//! (Material Icon Theme {version}, MIT, assets/explorer-icons/LICENSE),\n"
            "//! embedded so the app needs no files beside it. Sorted by name for a\n"
            "//! binary search; `explorer_icons.rs` serves them to gpui.\n\n"
            "pub const SVGS: &[(&str, &[u8])] = &[\n"
        )
        for icon in used:
            f.write(
                f"    ({rust_str(icon)}, include_bytes!(\"../../assets/explorer-icons/{icon}.svg\")),\n"
            )
        f.write("];\n")

    print(f"{len(used)} icons, {len(names)} file names, {len(exts)} extensions ({version})")


if __name__ == "__main__":
    main()
